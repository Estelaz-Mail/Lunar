--- The Cloudflare Workers target.
--
-- The shape is the one a Rust Worker uses: the application is compiled to
-- something the edge runtime can execute, and a small JavaScript entry point
-- hands it the request and returns its response. For Rust that artifact is
-- WebAssembly; here it is one Lua file running on Fengari, a Lua virtual
-- machine written in JavaScript — no WebAssembly toolchain, and the same code
-- that runs behind the HTTP server.
--
-- What this generates is a complete, deployable directory:
--
--   wrangler.jsonc      the Worker, its assets and its module rules
--   package.json        one dependency, fengari
--   src/worker.mjs      the entry point: fetch in, fetch out
--   src/app.lua         the whole app in one file, imported as text
--   src/fs-stub.cjs     what Fengari's `fs` import resolves to on the edge
--   src/tmp-stub.cjs    the same for `tmp`
--   src/absent.cjs      the same for `readline-sync` and `child_process`
--   public/             the static files, served by the platform
--
-- Nothing in `src/app.lua` opens a file or a socket: the route table, the
-- components and the probes are all in it, which is what makes a
-- filesystem-less runtime possible at all.

local bundle = require("lunar.site.bundle")
local fs = require("lunar.core.fs")
local json = require("lunar.core.json")
local util = require("lunar.core.util")

local workers = {}

--- A Worker name has to be a hostname label.
local function worker_name(name)
  local cleaned = tostring(name or "lunar"):lower():gsub("[^%w%-]", "-")
  cleaned = cleaned:gsub("%-+", "-"):gsub("^%-", ""):gsub("%-$", "")
  if cleaned == "" then cleaned = "lunar-app" end
  return cleaned:sub(1, 54)
end

local function today()
  return os.date("!%Y-%m-%d")
end

--- `wrangler.jsonc`, with the comments that explain the three choices in it
-- that are not obvious.
local function wrangler_config(app, options)
  local name = worker_name(options.name or app.name)
  return string.format([[
{
	// Generated by `lunar workers`. Safe to edit: regenerating writes this
	// file again, so keep anything you add in a separate config or pass
	// `--no-config`.
	"$schema": "node_modules/wrangler/config-schema.json",
	"name": %s,
	"main": "src/worker.mjs",
	"compatibility_date": %s,

	// Fengari reaches for `process` and `Buffer` in its os and io libraries.
	// `fs` and `tmp` are aliased below instead of polyfilled: both are bound
	// as those libraries load, before any Lua runs, and a polyfill for a
	// filesystem a Worker does not have would be a lie.
	"compatibility_flags": ["nodejs_compat"],
	"alias": {
		"fs": "./src/fs-stub.cjs",
		"tmp": "./src/tmp-stub.cjs",
		"readline-sync": "./src/absent.cjs",
		"child_process": "./src/absent.cjs"
	},

	// `app.lua` is imported by `src/worker.mjs` as a string. Without this rule
	// the bundler would try to read it as JavaScript.
	"rules": [{ "type": "Text", "globs": ["**/*.lua"], "fallthrough": false }],

	// The stylesheet, the moonlight bundle and Fengari itself. The platform
	// answers for anything that matches a file here and only calls the Worker
	// for what does not, which is every page and every endpoint.
	"assets": {
		"directory": "./public/",
		"binding": "ASSETS"
	},

	"observability": { "enabled": true, "head_sampling_rate": 1 }
}
]], json.encode(name), json.encode(options.compatibility_date or today()))
end

local function package_json(app, options)
  return json.encode({
    name = worker_name(options.name or app.name),
    private = true,
    type = "module",
    scripts = {
      dev = "wrangler dev",
      deploy = "wrangler deploy",
    },
    dependencies = { fengari = options.fengari or "^0.1.4" },
    devDependencies = { wrangler = options.wrangler or "^4" },
  }) .. "\n"
end

local README = [[
# %s — on Cloudflare Workers

Generated by `lunar workers`. The whole app is `src/app.lua`: the framework,
every component, every probe and the route table, in one file with no
filesystem access. `src/worker.mjs` runs it on Fengari and turns the result
into a `Response`.

```sh
npm install
npx wrangler dev       # http://localhost:8787
npx wrangler deploy
```

## What is where

| Path              | What it is                                                  |
| ----------------- | ----------------------------------------------------------- |
| `src/app.lua`     | the app, frozen: routes, components, loads, the runtime      |
| `src/worker.mjs`  | the entry point; edit it to add a binding or a cache         |
| `src/fs-stub.cjs` | what Fengari's `fs` import resolves to; a Worker has no disk |
| `src/tmp-stub.cjs`| the same for `tmp`, which Fengari's os library pulls in   |
| `src/absent.cjs`  | `readline-sync` and `child_process`: no terminal, no fork |
| `public/`         | the static files, served by the platform before the Worker   |
| `wrangler.jsonc`  | the Worker, its assets, its module rules                     |

## Regenerating

```sh
lunar workers %s --out %s
```

Everything here is written again, so put anything of your own somewhere else.

## What is different from running it yourself

- **No sockets.** `lunar/http/server.lua` is not in the bundle; the platform
  is the server. Everything above it — the router, the render pipeline, the
  security headers — is exactly the same code.
- **Static files are the platform's.** `public/` is served by the assets
  binding, so `lunar/http/static.lua` never runs.
- **The rate limiter counts per isolate.** It is a token bucket in memory, and
  the edge has many isolates. For a real limit at the edge, use Cloudflare's
  own rate limiting rules in front of the Worker; what is in the app is a
  floor, not a ceiling.
- **A response is a string.** The bridge between JavaScript and Lua is JSON,
  so a route that wants to stream is a route that does not belong in Lunar.
]]

--- Copies a directory, keeping its shape. Returns how many files it wrote.
local function copy_tree(from, to)
  local written = 0
  for _, relative in ipairs(fs.files(from)) do
    local ok, err = fs.copy(fs.join(from, relative), fs.join(to, relative))
    if not ok then return nil, err end
    written = written + 1
  end
  return written
end

--- Builds the deploy directory. `options` is `{ out, name, compatibility_date,
-- entry, config, security, rate_limit }`.
function workers.generate(app, options)
  options = options or {}
  local out = options.out or fs.join(app.root, ".lunar", "workers")
  local framework = fs.join(app.framework, "lunar", "site", "targets", "workers")

  local written = {}
  local function write(relative, contents)
    local path = fs.join(out, relative)
    fs.mkdirp(fs.dirname(path))
    if not fs.write(path, contents) then
      return nil, path .. ": could not be written"
    end
    written[#written + 1] = { path = relative, bytes = #contents }
    return true
  end

  -- The app, frozen.
  local server, server_error = bundle.server(app, {
    security = options.security,
    rate_limit = options.rate_limit,
  })
  if not server then return nil, server_error end
  local ok, err = write("src/app.lua", server)
  if not ok then return nil, err end

  -- The entry point and the stub it needs. Both are copied rather than
  -- generated: they are ordinary files in the framework, and a reader should
  -- be able to open the one in `lunar/site/targets/workers/` and see exactly
  -- what ends up deployed.
  if options.entry ~= false then
    local entry = fs.read(fs.join(framework, "worker.mjs"))
    if not entry then return nil, "worker.mjs is missing from the framework" end
    local wrote, write_error = write("src/worker.mjs", entry)
    if not wrote then return nil, write_error end
  end

  for _, stub in ipairs({ "fs-stub.cjs", "tmp-stub.cjs", "absent.cjs" }) do
    local contents = fs.read(fs.join(framework, stub))
    if not contents then return nil, stub .. " is missing from the framework" end
    write("src/" .. stub, contents)
  end

  if options.config ~= false then
    write("wrangler.jsonc", wrangler_config(app, options))
    write("package.json", package_json(app, options))
  end

  write("README.md", string.format(README, app.name, app.root, out))
  write(".gitignore", table.concat({
    "node_modules/", ".wrangler/", "*.log", "",
  }, "\n"))

  -- The static files: the app's own, then the two the client half needs.
  local public = fs.join(out, "public")
  local static_root = fs.join(app.root, "static")
  if fs.exists(fs.join(static_root, ".")) or #fs.files(static_root) > 0 then
    local count, copy_error = copy_tree(static_root, public)
    if not count then return nil, copy_error end
    written[#written + 1] = { path = "public/", bytes = 0, files = count }
  end

  if app.client ~= false then
    local moonlight, moonlight_error = bundle.build(app)
    if not moonlight then return nil, moonlight_error end
    write("public/_lunar/moonlight.lua", moonlight)

    local fengari = fs.read(fs.join(app.framework, "static", "vendor", "fengari-web.js"))
    if not fengari then
      return nil, "fengari-web.js is missing from the framework's static/vendor"
    end
    write("public/_lunar/fengari.js", fengari)
  end

  return { out = out, files = written }
end

workers.worker_name = worker_name
workers.wrangler_config = wrangler_config

return workers
